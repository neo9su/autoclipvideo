async page => {
  const modal = page.locator('.modal')
  await modal.getByRole('option', { name: '颜遇生活 (douyin)', exact: true }).waitFor({ state: 'attached' })
  const search = modal.getByRole('searchbox', { name: '搜索分组视频' })
  await search.fill('人生 红棕')
  if (await modal.getByRole('checkbox', { name: /^选择视频/ }).count() !== 1) throw Error('Fuzzy search did not narrow to one group')
  await modal.getByRole('checkbox', { name: /^选择视频.*人生/ }).check()
  await modal.getByPlaceholder('最多25字').fill('人生独立文案')
  await modal.getByPlaceholder('100-200字，含卖点和互动引导').fill('人生说明只属于第一条视频')
  await modal.getByRole('checkbox', { name: '人生 同名商品', exact: true }).nth(0).check()
  await modal.getByRole('checkbox', { name: '人生 同名商品', exact: true }).nth(1).check()
  await search.fill('夺回')
  await modal.getByRole('checkbox', { name: /^选择视频.*夺回/ }).check()
  if (await modal.getByPlaceholder('最多25字').inputValue()) throw Error('Copy leaked to second video')
  if (!await modal.getByRole('checkbox', { name: '人生 同名商品', exact: true }).nth(0).isChecked()) throw Error('Shared cart did not follow video selection')
  await modal.getByPlaceholder('最多25字').fill('夺回独立文案')
  await modal.getByPlaceholder('100-200字，含卖点和互动引导').fill('夺回说明只属于第二条视频')
  await modal.getByRole('checkbox', { name: '夺回 商品', exact: true }).check()
  await modal.getByRole('button', { name: /^编辑 codex · 11/ }).click()
  if (await modal.getByPlaceholder('最多25字').inputValue() !== '人生独立文案') throw Error('Draft was not restored')
  if (!await modal.getByRole('checkbox', { name: '人生 同名商品', exact: true }).nth(1).isChecked()) throw Error('Product draft was not restored')
  await search.fill('天蝎座')
  if (!await modal.getByText('未找到匹配的视频，请更换关键词').isVisible()) throw Error('No-result feedback missing')
  await modal.getByRole('button', { name: 'KUKU公主', exact: true }).click()
  if (await modal.getByRole('checkbox', { name: /^选择视频.*天蝎座/ }).count() !== 1) throw Error('Room filter not combined with search')
  if (!await modal.getByText('已选 2 个视频', { exact: false }).isVisible()) throw Error('Filtering cleared selection')
  await modal.getByRole('button', { name: '全部', exact: true }).click()
  await search.fill('')
  await page.screenshot({ path: 'output/playwright/publish-selection-before-submit.png', fullPage: true })
  await modal.getByRole('button', { name: '创建 2 个发布任务', exact: true }).click()
  await page.waitForFunction(() => window.__publishFixturePosts?.length === 2)
  await page.waitForFunction(() => !document.querySelector('.modal'))
  const posts = await page.evaluate(() => window.__publishFixturePosts)
  if (JSON.stringify(posts.map(p => p.group_id)) !== '[11,12]') throw Error('Not one independent task per selected video')
  if (JSON.stringify(posts.map(p => p.title)) !== '["人生独立文案","夺回独立文案"]') throw Error('Copy mixed across tasks')
  if (JSON.stringify(posts.map(p => p.product_ids)) !== '[[101,102,201],[101,102,201]]') throw Error('Batch cart is not identical across tasks')
  if (posts.some(p => p.publish_version !== 'codex' || p.account_id !== 9 || p.auto_meta)) throw Error('Task version/account/meta mismatch')
  if ((await page.evaluate(() => window.__unexpectedMutations || [])).length) throw Error('Unexpected mutation was attempted')
  return { mock_only: true, task_count: posts.length, group_ids: posts.map(p => p.group_id), product_ids: posts.map(p => p.product_ids), copy_isolated: true }
}
